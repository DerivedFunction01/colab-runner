# The multi-lease lifecycle at the module seam: a stateful
# in-process fake of the colab callable drives lease.acquire/reap/
# release against a scratch repo (config + symlinked snippets), so
# the exact CLI calls issued are assertable.

import importlib.util

_spec = importlib.util.spec_from_file_location("lease_mod", REPO / "sync" / "lease.py")
lease_mod = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(lease_mod)

PNOW = datetime(2026, 10, 29, 18, 0, tzinfo=timezone.utc)


class FakeColab:
    """Stateful fake of the injected colab callable: a session set
    plus a full call log."""

    def __init__(self, alive=()):
        self.alive = set(alive)
        self.calls = []

    def __call__(self, *a, **k):
        self.calls.append(a)
        cmd = a[0] if a else ""
        if cmd == "usage":
            return subprocess.CompletedProcess([], 0, "balance: 500 CU (fake)", "")
        if cmd == "sessions":
            return subprocess.CompletedProcess([], 0, json.dumps(sorted(self.alive)), "")
        if cmd == "new":
            self.alive.add(a[a.index("-s") + 1])
            return subprocess.CompletedProcess([], 0, "created", "")
        if cmd == "stop":
            self.alive.discard(a[a.index("-s") + 1])
            return subprocess.CompletedProcess([], 0, "stopped", "")
        if cmd == "download":
            return subprocess.CompletedProcess([], 1, "", "")
        return subprocess.CompletedProcess([], 0, "", "")

    def verbs(self):
        return [c[0] for c in self.calls if c]


def scratch_repo(tmp_path, monkeypatch, daily_cap=15):
    cfg_dir = tmp_path / "config"
    cfg_dir.mkdir(parents=True, exist_ok=True)
    # The measured-rate table seeds the shape rates: cpu at the
    # Standard rate, cpu-highram at the High-RAM rate.
    var_dir = tmp_path / "var"
    var_dir.mkdir(parents=True, exist_ok=True)
    (var_dir / "shape-rates.json").write_text(json.dumps({"cpu": 0.08, "cpu-highram": 0.26}))
    (cfg_dir / "lease.json").write_text(json.dumps({
        "enabled": True, "daily_cu_budget": daily_cap, "monthly_cu_budget": 150, "max_hours": 8,
        "keepalive": {"enabled": True, "interval_seconds": 60, "pulse_seconds": 600, "stale_seconds": 600},
        # Permissive fixture state for the session shape gate: the
        # general suite predates it; the gate's own tests below run
        # under an enforcing fixture (gate_repo).
        "session_gate": {"enabled": False},
    }, sort_keys=True, separators=(",", ":")))
    (tmp_path / "snippets").symlink_to(REPO / "snippets")
    monkeypatch.setenv("COLAB_RUNNER_VAR", str(tmp_path / "var"))
    # A scratch HOME keeps the local sessions binding (which the
    # post-start shape assertion reads) out of these in-process
    # tests: the real binding belongs to live sessions.
    monkeypatch.setenv("HOME", str(tmp_path / "home"))
    return tmp_path


def test_second_caller_rides_the_existing_lease(tmp_path, monkeypatch):
    """A session is shared capacity (operator ruling, 2026-11-05):
    a second caller at the same shape uses the first caller's live
    lease — no new session is created, the record keeps its
    creator's stamp, and the ride is journaled as the rider's
    claim. Attribution is knowing who called, never a gate on use."""
    repo = scratch_repo(tmp_path, monkeypatch)
    fake = FakeColab()
    a = lease_mod.acquire(fake, repo, "cpu", now_dt=PNOW, caller="alpha")
    b = lease_mod.acquire(fake, repo, "cpu", now_dt=PNOW, caller="beta")
    assert a["action"] == "created"
    assert b["action"] == "adopted"
    assert b["record"]["session"] == a["record"]["session"]
    assert b["riding"] is True and b["owner_caller"] == "alpha"
    assert not [c for c in fake.calls if c[0] == "new" and "-s" in c and c[-1] != a["record"]["session"]]
    assert len(lease_mod.all_records(repo)) == 1
    assert lease_mod.all_records(repo)[0]["caller"] == "alpha"
    claims = lease_mod.load_caller_claims(repo)
    assert claims[a["record"]["session"]]["caller"] == "beta"


